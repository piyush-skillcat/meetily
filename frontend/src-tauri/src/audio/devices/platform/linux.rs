use anyhow::Result;
use cpal::traits::{DeviceTrait, HostTrait};

use crate::audio::devices::configuration::{AudioDevice, DeviceType};

/// Configure Linux audio devices using ALSA/PulseAudio
pub fn configure_linux_audio(host: &cpal::Host) -> Result<Vec<AudioDevice>> {
    let mut devices = Vec::new();

    // Make sure the generated monitor PCM exists (and tracks the current default sink)
    let _ = ensure_system_monitor_pcm();

    // Add input devices
    for device in host.input_devices()? {
        if let Ok(name) = device.name() {
            devices.push(AudioDevice::new(name, DeviceType::Input));
        }
    }

    // Add PulseAudio monitor sources for system audio
    if let Ok(pulse_host) = cpal::host_from_id(cpal::HostId::Alsa) {
        for device in pulse_host.input_devices()? {
            if let Ok(name) = device.name() {
                // Check if it's a monitor source
                if name.contains("monitor") {
                    devices.push(AudioDevice::new(
                        format!("{} (System Audio)", name),
                        DeviceType::Output
                    ));
                }
            }
        }
    }

    Ok(devices)
}
// ============================================================================
// System-audio capture on PipeWire/PulseAudio desktops
//
// cpal only speaks ALSA on Linux, and ALSA has no built-in way to record what
// the speakers are playing. We expose the PipeWire/Pulse *monitor* of the
// default output sink as an ALSA capture PCM by generating a tiny ALSA config
// and pointing ALSA_CONFIG_PATH at it (process-local; nothing in $HOME is
// touched). The PCM name contains "monitor" so the rest of the app treats it
// as the system-audio device.
// ============================================================================

use log::{info, warn};
use std::path::PathBuf;
use std::process::Command;
use std::sync::OnceLock;

pub const MEETILY_MONITOR_PCM: &str = "meetily_system_monitor";
static ALSA_CONFIG_INSTALLED: OnceLock<bool> = OnceLock::new();

fn run_cmd(cmd: &str, args: &[&str]) -> Option<String> {
    let out = Command::new(cmd).args(args).output().ok()?;
    if !out.status.success() {
        return None;
    }
    let s = String::from_utf8_lossy(&out.stdout).trim().to_string();
    if s.is_empty() { None } else { Some(s) }
}

/// Name of the monitor source for the default output sink, e.g.
/// `alsa_output.pci-0000_64_00.6.HiFi__Speaker__sink.monitor`.
pub fn default_sink_monitor() -> Option<String> {
    if let Some(sink) = run_cmd("pactl", &["get-default-sink"]) {
        return Some(format!("{}.monitor", sink));
    }
    // Older pactl: parse the first sink
    if let Some(list) = run_cmd("pactl", &["list", "short", "sinks"]) {
        if let Some(line) = list.lines().next() {
            if let Some(name) = line.split_whitespace().nth(1) {
                return Some(format!("{}.monitor", name));
            }
        }
    }
    // Any existing monitor source
    if let Some(list) = run_cmd("pactl", &["list", "short", "sources"]) {
        for line in list.lines() {
            if let Some(name) = line.split_whitespace().nth(1) {
                if name.ends_with(".monitor") {
                    return Some(name.to_string());
                }
            }
        }
    }
    None
}

fn alsa_plugin_available(name: &str) -> bool {
    [
        "/usr/lib64/alsa-lib",
        "/usr/lib/x86_64-linux-gnu/alsa-lib",
        "/usr/lib/aarch64-linux-gnu/alsa-lib",
        "/usr/lib/alsa-lib",
    ]
    .iter()
    .any(|dir| PathBuf::from(dir).join(format!("libasound_module_pcm_{}.so", name)).exists())
}

fn monitor_config_path() -> Option<PathBuf> {
    let mut p = dirs::config_dir()?;
    p.push("Meetily");
    std::fs::create_dir_all(&p).ok()?;
    p.push("asound-system-monitor.conf");
    Some(p)
}

/// Write (or refresh) the ALSA PCM definition for the current default sink's
/// monitor. Safe to call before every recording: alsa-lib re-reads changed
/// config files on the next `snd_pcm_open`.
///
/// Returns the PCM name when a monitor could be exposed.
pub fn ensure_system_monitor_pcm() -> Option<String> {
    let monitor = match default_sink_monitor() {
        Some(m) => m,
        None => {
            warn!("No PipeWire/PulseAudio sink found; system audio capture unavailable");
            return None;
        }
    };

    let body = if alsa_plugin_available("pipewire") {
        format!(
            "# Generated by Meetily; exposes the default output's monitor for system-audio capture.\n\
             pcm.{name} {{\n    type pipewire\n    playback_node \"-1\"\n    capture_node \"{monitor}\"\n    hint {{ show on\n           description \"System Audio (what you hear)\" }}\n}}\n",
            name = MEETILY_MONITOR_PCM,
            monitor = monitor
        )
    } else if alsa_plugin_available("pulse") {
        format!(
            "# Generated by Meetily; exposes the default output's monitor for system-audio capture.\n\
             pcm.{name} {{\n    type pulse\n    device \"{monitor}\"\n    hint {{ show on\n           description \"System Audio (what you hear)\" }}\n}}\n",
            name = MEETILY_MONITOR_PCM,
            monitor = monitor
        )
    } else {
        warn!("Neither the pipewire nor the pulse ALSA plugin is installed (alsa-plugins-pipewire / alsa-plugins-pulseaudio); system audio capture unavailable");
        return None;
    };

    let path = monitor_config_path()?;
    let unchanged = std::fs::read_to_string(&path).map(|cur| cur == body).unwrap_or(false);
    if !unchanged {
        if let Err(e) = std::fs::write(&path, &body) {
            warn!("Failed to write ALSA monitor config {:?}: {}", path, e);
            return None;
        }
        info!("System-audio monitor PCM '{}' → {} ({:?})", MEETILY_MONITOR_PCM, monitor, path);
    }

    // Point alsa-lib at our file. Must happen before the first ALSA call in
    // this process, so `run()` calls this at startup.
    ALSA_CONFIG_INSTALLED.get_or_init(|| {
        let base = std::env::var("ALSA_CONFIG_PATH")
            .ok()
            .filter(|s| !s.trim().is_empty())
            .unwrap_or_else(|| "/usr/share/alsa/alsa.conf".to_string());
        let ours = path.to_string_lossy().to_string();
        if !base.split(':').any(|p| p == ours) {
            std::env::set_var("ALSA_CONFIG_PATH", format!("{}:{}", base, ours));
        }
        true
    });

    Some(MEETILY_MONITOR_PCM.to_string())
}

/// Best ALSA capture PCM for system audio: our generated monitor first, then
/// any user-defined PCM whose name mentions "monitor".
pub fn find_system_monitor_device(host: &cpal::Host) -> Option<AudioDevice> {
    let mut candidates: Vec<String> = Vec::new();
    if let Ok(devices) = host.input_devices() {
        for device in devices {
            if let Ok(name) = device.name() {
                if name.contains("monitor") {
                    candidates.push(name);
                }
            }
        }
    }
    candidates.sort_by_key(|n| if n == MEETILY_MONITOR_PCM { 0 } else { 1 });
    candidates.into_iter().next().map(|n| AudioDevice::new(n, DeviceType::Output))
}
